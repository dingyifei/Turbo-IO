"""Move the firmware tree between stock bases with the committed rebase table. Never connects to a device.

  python3 -I firmware/tools/rebase_apply.py --check            # the tree is wholly on build-inputs.json stockBase
  python3 -I firmware/tools/rebase_apply.py --check --stock ZIP # ... and its patch sites, trampoline prologues,
                                                                #     shim literals and strings match that stock ZIP
  python3 -I firmware/tools/rebase_apply.py --write --to 1.0.5.12

The table is firmware/baseline/rebase-1.0.5.5-to-1.0.5.12.json, generated by rebase_derive.py (see there for how
each value was derived and checked). This script never computes an address: it only swaps the table's `old` and
`new` columns. It rewrites

  link.ld           the 153 stock callee symbols (by name) and the module start `. = moduleVA`;
  build-inputs.json stockBase, stockZIP, stockAP, stockMembers, moduleVA, and for each of the 25 edits (by role)
                    offset, address and before. The two edits after FUN_10666c34 get their re-recorded `before`
                    (the BL inside the pattern re-encoded to the moved callee). `after`, the module, AP and archive
                    pins go stale until `build.py --repin`, which re-derives them;
  every value site  each literal in `values` (trampolines.S shim pointer and file-callback struct, coexist.S strings,
                    the launcher global, display unit and native_light RAM addresses, render dispatch values, and the
                    two addresses quoted in comments), at exactly the files and counts the table lists.

The 14 trampoline prologues in trampolines.S are byte-identical in both bases and are not touched; build.py checks
them against the stock bytes at every build. Thumb bit: see the table's thumbConvention (values are swapped exactly
as written, so the bit is preserved; --check asserts it).

`--check` fails on a mixed tree (some values on one base, some on the other) and on any old-base literal left
anywhere under src/, include/ and tests/, so a stale address cannot hide in a newly added file. build.py runs the same
check before every build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import zipfile

FW = Path(__file__).resolve().parents[1]
TABLE = FW/'baseline'/'rebase-1.0.5.5-to-1.0.5.12.json'
FLASH = 0x10190000
DATA_RUNTIME, DATA_FILE = 0x18000000, 0x401bc
SCANNED = ('src', 'include', 'tests', 'link.ld', 'trampolines.S', 'ImageWireFormat.h')
LINK_SYMBOL = re.compile(r'^(\s*)(\w+)(\s*=\s*)(0x[0-9a-fA-F]+)(;.*)$')
MODULE_START = re.compile(r'^(\s*\.\s*=\s*)(0x[0-9a-fA-F]+)(;.*)$')


def load_table(path=TABLE):
    table = json.loads(Path(path).read_text())
    assert table['format'] == 'turboio-rebase-1'
    return table


def token(value):
    return re.compile(r'(?<![0-9A-Za-z_])' + re.escape(value) + r'(?![0-9A-Za-z_])', re.I)


def column(table, base):
    """'old' or 'new' for a stock base named in the table."""
    if base == table['from']:
        return 'old'
    if base == table['to']:
        return 'new'
    raise SystemExit('stock base %r is not in the rebase table (%s, %s)' % (base, table['from'], table['to']))


def other(col):
    return 'new' if col == 'old' else 'old'


def scanned_files(fw):
    for part in SCANNED:
        p = fw/part
        for q in ([p] if p.is_file() else sorted(x for x in p.rglob('*') if x.is_file())):
            try:
                yield q, q.read_text()
            except UnicodeDecodeError:
                continue


def problems(fw, table, base):
    """Everything in the tree that is not on `base`. Empty list: the tree is wholly on `base`."""
    col = column(table, base)
    out = []
    spec = json.loads((fw/'build-inputs.json').read_text())
    info = table['bases'][base]
    if spec.get('stockBase') != base:
        out.append('build-inputs.json stockBase is %r' % spec.get('stockBase'))
    for key in ('stockZIP', 'stockAP', 'stockMembers'):
        if spec.get(key) != info[key]:
            out.append('build-inputs.json %s is not the %s stock' % (key, base))
    if spec.get('moduleVA') != table['moduleVA'][col]:
        out.append('build-inputs.json moduleVA %s' % spec.get('moduleVA'))
    by_role = {e['role']: e for e in spec['edits']}
    for row in table['edits']:
        e = by_role.get(row['role'])
        want = {'offset': row[col + 'Offset'], 'address': row[col + 'Address'], 'before': row[col + 'Before']}
        if e is None or {k: e[k] for k in want} != want:
            out.append('edit %r is not on %s' % (row['role'], base))
    if len(by_role) != len(table['edits']) or len(spec['edits']) != 25:
        out.append('build-inputs.json edits do not match the table roles')
    symbols, module = {}, []
    for line in (fw/'link.ld').read_text().splitlines():
        m = LINK_SYMBOL.match(line)
        if m:
            symbols[m.group(2)] = m.group(4).lower()
        m = MODULE_START.match(line)
        if m:
            module.append(m.group(2).lower())
    want = {r['symbol']: r[col] for r in table['linkld']}
    if symbols != want:
        bad = sorted(s for s in set(symbols) | set(want) if symbols.get(s) != want.get(s))
        out.append('link.ld symbols not on %s: %s' % (base, ', '.join(bad[:8]) + (' ...' if len(bad) > 8 else '')))
    for r in table['linkld']:
        if int(r['old'], 16) & 1 != int(r['new'], 16) & 1:
            out.append('table Thumb bit differs for ' + r['symbol'])
    if module != [table['moduleVA'][col]]:
        out.append('link.ld module start %s' % module)
    texts = {q.relative_to(fw).as_posix(): t for q, t in scanned_files(fw)}
    for v in table['values']:
        good, stale = token(v[col]), token(v[other(col)])
        for path, text in texts.items():
            n_good, n_stale = len(good.findall(text)), len(stale.findall(text))
            expect = v['sites'].get(path, 0)
            if n_stale:
                out.append('%s: %d stale %s (%s, %s value)' % (path, n_stale, v[other(col)], v['name'], other(col)))
            if n_good != expect:
                out.append('%s: %d x %s (%s), table says %d' % (path, n_good, v[col], v['name'], expect))
        if v['kind'] == 'code' and int(v['old'], 16) & 1 != int(v['new'], 16) & 1:
            out.append('table Thumb bit differs for ' + v['name'])
    return out


def tree_state(fw=FW, table=None):
    """The one stock base the tree is wholly on; raises if it is on neither (mixed or unknown)."""
    table = table or load_table()
    reports = {}
    for base in (table['from'], table['to']):
        reports[base] = problems(fw, table, base)
        if not reports[base]:
            return base
    raise AssertionError('firmware tree is on neither stock base (mixed addresses?):\n' + '\n'.join(
        '  %s: %d problems, first: %s' % (b, len(p), p[0]) for b, p in reports.items()))


def write(fw, table, base):
    col = column(table, base)
    src = other(col)
    info = table['bases'][base]
    changed = []
    # build-inputs.json
    path = fw/'build-inputs.json'
    spec = json.loads(path.read_text())
    ordered = {}
    for key, value in spec.items():
        ordered[key] = value
        if key == 'stockAP':
            ordered['stockBase'] = base
            ordered['stockMembers'] = info['stockMembers']
    spec = ordered
    spec.update(stockBase=base, stockZIP=info['stockZIP'], stockAP=info['stockAP'], stockMembers=info['stockMembers'],
                moduleVA=table['moduleVA'][col])
    by_role = {e['role']: e for e in spec['edits']}
    for row in table['edits']:
        e = by_role[row['role']]
        assert {e['offset'], e['address'], e['before']} <= {row[k + s] for k in (col, src) for s in ('Offset', 'Address', 'Before')}, row['role']
        e.update(offset=row[col + 'Offset'], address=row[col + 'Address'], before=row[col + 'Before'])
    text = json.dumps(spec, indent=2) + '\n'
    if text != path.read_text():
        path.write_text(text)
        changed.append('build-inputs.json')
    # link.ld
    path = fw/'link.ld'
    want = {r['symbol']: (r[src], r[col]) for r in table['linkld']}
    lines = []
    for line in path.read_text().split('\n'):
        m = LINK_SYMBOL.match(line)
        if m and m.group(2) in want:
            assert m.group(4).lower() in want[m.group(2)], m.group(2)
            line = m.group(1) + m.group(2) + m.group(3) + want[m.group(2)][1] + m.group(5)
        m = MODULE_START.match(line)
        if m:
            assert m.group(2).lower() in (table['moduleVA']['old'], table['moduleVA']['new'])
            line = m.group(1) + table['moduleVA'][col] + m.group(3)
        lines.append(line)
    text = '\n'.join(lines)
    if text != path.read_text():
        path.write_text(text)
        changed.append('link.ld')
    # value sites
    for v in table['values']:
        for rel, count in v['sites'].items():
            path = fw/rel
            text = path.read_text()
            stale = token(v[src])
            assert len(stale.findall(text)) + len(token(v[col]).findall(text)) == count, (rel, v['name'])
            new_text = stale.sub(v[col], text)
            if new_text != text:
                path.write_text(new_text)
                changed.append(rel)
    return sorted(set(changed))


def check_stock(fw, table, stock_zip):
    """The tree's patch sites, trampoline prologues, shim literals and strings against one stock ZIP."""
    spec = json.loads((fw/'build-inputs.json').read_text())
    with zipfile.ZipFile(stock_zip) as z:
        ap = z.read('nuttx_ap.bin')
    assert hashlib.sha256(ap).hexdigest() == spec['stockAP'], 'stock ZIP is not the tree stockAP'
    col = column(table, spec['stockBase'])
    out = []
    for e in spec['edits']:
        at = int(e['offset'], 16)
        if ap[at:at + len(bytes.fromhex(e['before']))].hex() != e['before']:
            out.append('edit %r before bytes' % e['role'])
    tramp = (fw/'trampolines.S').read_text()
    for e in spec['edits']:
        if e['role'].startswith('Entry trampoline '):
            name = e['role'].removeprefix('Entry trampoline ')
            m = re.search(r'^stock_' + name + r':\n\.byte ([^\n]+)\nb\.w resume_' + name + r'$', tramp, re.M)
            data = bytes(int(x, 0) for x in m.group(1).split(',')) if m else b''
            if data != bytes.fromhex(e['before']):
                out.append('trampoline prologue ' + name)
    values = {v['name']: int(v[col], 16) for v in table['values']}
    reg = next(e for e in spec['edits'] if e['role'] == 'File callback registration')
    site = int(reg['address'], 16)
    for k, name in ((2, 'file_callback_struct'), (4, 'stream_register_target')):
        g = struct.unpack_from('<H', ap, site + k - FLASH)[0]
        literal = struct.unpack_from('<I', ap, ((site + k + 4) & ~3) + (g & 0xff) * 4 - FLASH)[0]
        if (g & 0xf800) != 0x4800 or literal != values[name]:
            out.append('stock registration literal for ' + name)
    for v in table['values']:
        if v['kind'] == 'data':
            text = v['string']
            at = DATA_FILE + int(v[col], 16) - DATA_RUNTIME
            if ap[at:at + len(text) + 1] != text.encode() + b'\0':
                out.append('data string ' + v['name'])
    return out


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    parser.add_argument('--to', help='stock base to write (--write)')
    parser.add_argument('--base', help='stock base to check (default: build-inputs.json stockBase)')
    parser.add_argument('--stock', type=Path, help='stock ZIP of that base (--check)')
    parser.add_argument('--tree', type=Path, default=FW)
    parser.add_argument('--table', type=Path, default=TABLE)
    args = parser.parse_args()
    fw = args.tree.resolve()
    table = load_table(args.table)
    if args.write:
        if not args.to:
            parser.error('--write needs --to')
        changed = write(fw, table, args.to)
        left = problems(fw, table, args.to)
        if left:
            raise SystemExit('tree still not on %s:\n  %s' % (args.to, '\n  '.join(left)))
        print(json.dumps({'stockBase': args.to, 'changed': changed}, indent=2))
        return
    base = args.base or json.loads((fw/'build-inputs.json').read_text()).get('stockBase')
    left = problems(fw, table, base)
    if args.stock and not left:
        left = check_stock(fw, table, args.stock)
    if left:
        raise SystemExit('REBASE CHECK FAIL (%s):\n  %s' % (base, '\n  '.join(left)))
    print('PASS rebase: tree wholly on stock %s (%d link.ld callees, 25 edits, %d value sites%s)' % (
        base, len(table['linkld']), sum(sum(v['sites'].values()) for v in table['values']),
        '; patch sites, trampoline prologues, registration literals and strings match the stock ZIP' if args.stock else ''))


if __name__ == '__main__':
    sys.exit(main())
