"""Move the firmware tree between stock bases with the committed rebase table. Never connects to a device.

  python3 -I firmware/tools/rebase_apply.py --check            # the tree is wholly on build-inputs.json stockBase
  python3 -I firmware/tools/rebase_apply.py --check --stock ZIP # ... and its patch sites, trampoline prologues,
                                                                #     shim literals and strings match that stock ZIP
  python3 -I firmware/tools/rebase_apply.py --write --to 1.0.5.12

The table is the last file of TABLES that exists in firmware/baseline/ (today rebase-1.0.5.5-to-1.0.5.12.json, format
turboio-rebase-1; the 1.0.5.12 to 1.0.6.11 file, format turboio-rebase-2, activates itself when it is committed),
generated by rebase_derive.py (see there for how each value was derived and checked). The PASS line names the table
file. This script never computes an address: it only swaps the table's `old` and `new` columns. It rewrites

  link.ld           the 153 stock callee symbols (by name) and the module start `. = moduleVA`;
  build-inputs.json stockBase, stockZIP, stockAP, stockMembers, moduleVA, and for each edit of the table (by role)
                    offset, address and before, plus pad and (raw edits only) after when the table has them
                    (format 2). The two edits after FUN_10666c34 get their re-recorded `before` (the BL inside the
                    pattern re-encoded to the moved callee). `after` of the other edits, the module, AP and archive
                    pins go stale until `build.py --repin`, which re-derives them. stockManifestSHA256 is copied
                    when the base has one and removed otherwise;
  every value site  each literal in `values` (trampolines.S shim pointer and file-callback struct, coexist.S strings,
                    the launcher global, display unit and native_light RAM addresses, render dispatch values, and the
                    two addresses quoted in comments), at exactly the files and counts the table lists.

The trampoline prologues in trampolines.S are byte-identical in both bases and are not touched; build.py checks
them against the stock bytes at every build. The number of edits is the table's: build-inputs.json must hold exactly
the table's edit roles, and its editCount (when present; build.py requires it) must equal their number. Thumb bit: see the table's thumbConvention (values are swapped exactly
as written, so the bit is preserved; --check asserts it).

`--check` fails on a mixed tree (some values on one base, some on the other), on any old-base literal left
anywhere under src/, include/ and tests/, and on any hex token in a stock window (either base's AP flash, RAM
0x18000000-0x1b600000, the copy region) that is not an address of the tree's base in the table and not listed in the
table's notStock, so a stock address the table does not know cannot hide either. build.py runs the same check before
every build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct
import sys
import zipfile

FW = Path(__file__).resolve().parents[1]
# (from, to, file in firmware/baseline, format), oldest first. The last entry whose file exists is the active table.
TABLES = (('1.0.5.5', '1.0.5.12', 'rebase-1.0.5.5-to-1.0.5.12.json', 'turboio-rebase-1'),
          ('1.0.5.12', '1.0.6.11', 'rebase-1.0.5.12-to-1.0.6.11.json', 'turboio-rebase-2'))
FLASH = 0x10190000
DATA_RUNTIME = 0x18000000
DATA_DESCRIPTOR = 0x674   # file offset of the .data copy descriptor: <3I src, end, dst
# AP sha256 -> file offset delta (runtime VA - file offset) of the .data copy, for the images the tables know
KNOWN_DATA_DELTA = {'b3d6d9d7a4ece97e1dbaa64fc080eb5db8a5f7c9fecf340888ebb97a9112cc6c': 0x17fbfe44,   # 1.0.5.5
                    'af701a6525fbf703854b3d63e757734546c20bdb5d50e246867dc6a0565713ae': 0x17fbfe44,   # 1.0.5.12
                    '9bbf7be31ebb7f8600e6ea4bf51831a151e2af6d4eb8e6ccfcf55d67f2e71260': 0x17fbf49c}   # 1.0.6.11
SCANNED = ('src', 'include', 'tests', 'link.ld', 'trampolines.S', 'ImageWireFormat.h')
LINK_SYMBOL = re.compile(r'^(\s*)(\w+)(\s*=\s*)(0x[0-9a-fA-F]+)(;.*)$')
MODULE_START = re.compile(r'^(\s*\.\s*=\s*)(0x[0-9a-fA-F]+)(;.*)$')


def _existing(fw):
    """The TABLES entries whose file exists in fw/baseline. They must be a prefix of TABLES (no gap)."""
    have = [(Path(fw)/'baseline'/t[2]).is_file() for t in TABLES]
    assert have == sorted(have, reverse=True), 'rebase tables in %s are not a prefix of TABLES: %s' % (
        Path(fw)/'baseline', ', '.join(t[2] for t, h in zip(TABLES, have) if h))
    return [t for t, h in zip(TABLES, have) if h]


def active_table_path(fw=FW):
    """The last TABLES entry whose file exists in fw/baseline."""
    existing = _existing(fw)
    assert existing, 'no rebase table in %s' % (Path(fw)/'baseline')
    return Path(fw)/'baseline'/existing[-1][2]


def _read_table(path, entry=None):
    """Load one table file. `entry` is the TABLES entry it must be; None: the entry its from/to name."""
    table = json.loads(Path(path).read_text())
    found = next((t for t in TABLES if (t[0], t[1]) == (table.get('from'), table.get('to'))), None)
    assert found is not None, '%s: no TABLES entry for %r to %r' % (Path(path).name, table.get('from'), table.get('to'))
    assert entry is None or found == entry, '%s is not the table of %s to %s' % (Path(path).name, entry[0], entry[1])
    assert table.get('format') == found[3], '%s: format %r, TABLES says %s' % (Path(path).name, table.get('format'), found[3])
    if found[3] == 'turboio-rebase-2':
        assert table.get('rejected') == [], '%s: rejected rows are not empty (or missing)' % Path(path).name
    return table


def table_chain(fw=FW):
    """The loaded tables of fw/baseline in TABLES order (the existing files are a prefix of TABLES, and not empty)."""
    existing = _existing(fw)
    assert existing, 'no rebase table in %s' % (Path(fw)/'baseline')
    return [_read_table(Path(fw)/'baseline'/t[2], t) for t in existing]


def load_table(path=None, fw=FW):
    """The table at `path`, or the active table of `fw`. Refuses a file whose format, from or to disagree with TABLES,
    and a format-2 table with rejected rows."""
    if path is None:
        path = active_table_path(fw)
        return _read_table(path, next(t for t in TABLES if t[2] == path.name))
    return _read_table(path)


def data_copy(ap):
    """(src, end, dst, delta) of the .data copy from the descriptor of an AP image; delta = runtime VA - file offset."""
    assert len(ap) >= DATA_DESCRIPTOR + 12, 'AP image too short for the data copy descriptor'
    src, end, dst = struct.unpack_from('<3I', ap, DATA_DESCRIPTOR)
    assert dst == DATA_RUNTIME and FLASH <= src < end <= FLASH + len(ap), 'data copy descriptor is out of range'
    delta = dst - (src - FLASH)
    known = KNOWN_DATA_DELTA.get(hashlib.sha256(ap).hexdigest())
    assert known is None or known == delta, 'data copy delta %#x is not the known %#x for this image' % (delta, known)
    return src, end, dst, delta


def data_file_delta(ap):
    """Runtime VA minus file offset of the .data copy, read from the AP image (file offset = VA - delta)."""
    return data_copy(ap)[3]


def data_offset(ap, va):
    """File offset of the copied .data byte at runtime address `va`; va must lie in the copied range."""
    src, end, dst, delta = data_copy(ap)
    assert dst <= va < dst + (end - src), '%#x is not in the copied data range' % va
    return va - delta


HEX = re.compile(r'(?<![0-9A-Za-z_])0x([0-9a-fA-F]{1,8})(?![0-9A-Za-z_])')


def edit_column(row, col):
    """One edit row's values in column `col`: offset, address, before, and pad / raw after when the table has them."""
    out = {'offset': row[col + 'Offset'], 'address': row[col + 'Address'], 'before': row[col + 'Before']}
    for key in ('pad', 'after'):
        if col + key.capitalize() in row:
            out[key] = row[col + key.capitalize()]
    return out


def value_string(table, v, col):
    """The stock string of a data value row in column `col` (format 1: one string; format 2: oldString / newString)."""
    return v[col + 'String'] if table['format'] == 'turboio-rebase-2' else v['string']


def sites(v):
    """Value sites: those of the TMG9 tree the table was derived from, plus sites written after it."""
    out = dict(v['sites'])
    for f, c in v.get('addedSites', {}).items():
        out[f] = out.get(f, 0) + c
    return out


def leftovers(table, base, texts):
    """Every hex token in a stock window that is not an address of `base` and not listed as not-stock.

    Windows: the AP flash of either base (FLASH .. FLASH + AP bytes), RAM 0x18000000-0x1b600000 and the copy region
    0x100000-0x101000. Accounted for: the base's link.ld callees, value sites, edit addresses, module VA and stock
    ABI ranges. So a stock address the table does not know (a gap like the native_page.c comment that tmg10(5)
    found) fails the check whichever base it came from."""
    col = column(table, base)
    top = FLASH + max(b['stockAPBytes'] for b in table['bases'].values())
    known = {int(r[col], 16) for r in table['linkld']} | {int(v[col], 16) for v in table['values']}
    known |= {int(e[col + 'Address'], 16) for e in table['edits']} | {int(table['moduleVA'][col], 16)}
    known |= {int(r[col], 16) for r in table['stockAbiRanges']}
    known |= {int(t, 16) for t in table.get('notStock', {})}
    out = []
    for path, text in texts.items():
        if path in table.get('scanExempt', {}):
            continue
        for m in HEX.finditer(text):
            v = int(m.group(1), 16)
            if (FLASH <= v < top or 0x18000000 <= v < 0x1b600000 or 0x100000 <= v < 0x101000) and v not in known:
                out.append('%s: %s is in a stock window but is not a %s address in the table (stale or unknown)' % (path, m.group(0), base))
    return out


def token(value):
    return re.compile(r'(?<![0-9A-Za-z_])' + re.escape(value) + r'(?![0-9A-Za-z_])', re.I)


def column(table, base):
    """'old' or 'new' for a stock base named in the table."""
    if base == table['from']:
        return 'old'
    if base == table['to']:
        return 'new'
    raise SystemExit('stock base %r is not in the rebase table (%s, %s)' % (base, table['from'], table['to']))


def other(col):
    return 'new' if col == 'old' else 'old'


def scanned_files(fw):
    for part in SCANNED:
        p = fw/part
        for q in ([p] if p.is_file() else sorted(x for x in p.rglob('*') if x.is_file())):
            try:
                yield q, q.read_text()
            except UnicodeDecodeError:
                continue


def problems(fw, table, base):
    """Everything in the tree that is not on `base`. Empty list: the tree is wholly on `base`."""
    col = column(table, base)
    out = []
    spec = json.loads((fw/'build-inputs.json').read_text())
    info = table['bases'][base]
    if spec.get('stockBase') != base:
        out.append('build-inputs.json stockBase is %r' % spec.get('stockBase'))
    for key in ('stockZIP', 'stockAP', 'stockMembers'):
        if spec.get(key) != info[key]:
            out.append('build-inputs.json %s is not the %s stock' % (key, base))
    if ('stockManifestSHA256' in spec or 'stockManifestSHA256' in info) and spec.get('stockManifestSHA256') != info.get('stockManifestSHA256'):
        out.append('build-inputs.json stockManifestSHA256 is not the %s stock' % base)
    if spec.get('moduleVA') != table['moduleVA'][col]:
        out.append('build-inputs.json moduleVA %s' % spec.get('moduleVA'))
    by_role = {e['role']: e for e in spec['edits']}
    for row in table['edits']:
        e = by_role.get(row['role'])
        want = edit_column(row, col)
        if e is None or {k: e.get(k) for k in want} != want:
            out.append('edit %r is not on %s' % (row['role'], base))
    if len(by_role) != len(table['edits']) or len(spec['edits']) != len(table['edits']):
        out.append('build-inputs.json edits do not match the table roles')
    if 'editCount' in spec and spec['editCount'] != len(spec['edits']):   # build.py requires the key; an old tree export has none
        out.append('build-inputs.json editCount %r is not the number of edits (%d)' % (spec.get('editCount'), len(spec['edits'])))
    symbols, module = {}, []
    for line in (fw/'link.ld').read_text().splitlines():
        m = LINK_SYMBOL.match(line)
        if m:
            symbols[m.group(2)] = m.group(4).lower()
        m = MODULE_START.match(line)
        if m:
            module.append(m.group(2).lower())
    want = {r['symbol']: r[col] for r in table['linkld']}
    if symbols != want:
        bad = sorted(s for s in set(symbols) | set(want) if symbols.get(s) != want.get(s))
        out.append('link.ld symbols not on %s: %s' % (base, ', '.join(bad[:8]) + (' ...' if len(bad) > 8 else '')))
    for r in table['linkld']:
        if int(r['old'], 16) & 1 != int(r['new'], 16) & 1:
            out.append('table Thumb bit differs for ' + r['symbol'])
    if module != [table['moduleVA'][col]]:
        out.append('link.ld module start %s' % module)
    texts = {q.relative_to(fw).as_posix(): t for q, t in scanned_files(fw)}
    for v in table['values']:
        good, stale = token(v[col]), token(v[other(col)])
        for path, text in texts.items():
            n_good = len(good.findall(text))
            n_stale = 0 if v['old'].lower() == v['new'].lower() else len(stale.findall(text))   # an unchanged value is not stale
            expect = sites(v).get(path, 0)
            if n_stale:
                out.append('%s: %d stale %s (%s, %s value)' % (path, n_stale, v[other(col)], v['name'], other(col)))
            if n_good != expect:
                out.append('%s: %d x %s (%s), table says %d' % (path, n_good, v[col], v['name'], expect))
        if v['kind'] == 'code' and int(v['old'], 16) & 1 != int(v['new'], 16) & 1:
            out.append('table Thumb bit differs for ' + v['name'])
    out += leftovers(table, base, texts)
    return out


def tree_state(fw=FW, table=None):
    """The one stock base the tree is wholly on; raises if it is on neither (mixed or unknown)."""
    table = table or load_table(fw=fw)
    reports = {}
    for base in (table['from'], table['to']):
        reports[base] = problems(fw, table, base)
        if not reports[base]:
            return base
    raise AssertionError('firmware tree is on neither stock base (mixed addresses?):\n' + '\n'.join(
        '  %s: %d problems, first: %s' % (b, len(p), p[0]) for b, p in reports.items()))


def write(fw, table, base):
    col = column(table, base)
    src = other(col)
    info = table['bases'][base]
    changed = []
    # build-inputs.json
    path = fw/'build-inputs.json'
    spec = json.loads(path.read_text())
    manifest = info.get('stockManifestSHA256')
    ordered = {}
    for key, value in spec.items():
        if key == 'stockManifestSHA256' and manifest is None:
            continue
        ordered[key] = value
        if key == 'stockAP':
            ordered['stockBase'] = base
            ordered['stockMembers'] = info['stockMembers']
            if manifest is not None:
                ordered['stockManifestSHA256'] = manifest
    spec = ordered
    spec.update(stockBase=base, stockZIP=info['stockZIP'], stockAP=info['stockAP'], stockMembers=info['stockMembers'],
                moduleVA=table['moduleVA'][col])
    if manifest is not None:
        spec['stockManifestSHA256'] = manifest
    by_role = {e['role']: e for e in spec['edits']}
    for row in table['edits']:
        e = by_role[row['role']]
        want, was = edit_column(row, col), edit_column(row, src)
        assert all(e.get(k) in (want[k], was[k]) for k in want), row['role']
        e.update(want)
    text = json.dumps(spec, indent=2) + '\n'
    if text != path.read_text():
        path.write_text(text)
        changed.append('build-inputs.json')
    # link.ld
    path = fw/'link.ld'
    want = {r['symbol']: (r[src], r[col]) for r in table['linkld']}
    lines = []
    for line in path.read_text().split('\n'):
        m = LINK_SYMBOL.match(line)
        if m and m.group(2) in want:
            assert m.group(4).lower() in want[m.group(2)], m.group(2)
            line = m.group(1) + m.group(2) + m.group(3) + want[m.group(2)][1] + m.group(5)
        m = MODULE_START.match(line)
        if m:
            assert m.group(2).lower() in (table['moduleVA']['old'], table['moduleVA']['new'])
            line = m.group(1) + table['moduleVA'][col] + m.group(3)
        lines.append(line)
    text = '\n'.join(lines)
    if text != path.read_text():
        path.write_text(text)
        changed.append('link.ld')
    # value sites
    for v in table['values']:
        for rel, count in sites(v).items():
            path = fw/rel
            text = path.read_text()
            stale = token(v[src])
            same = v['old'].lower() == v['new'].lower()   # an unchanged value: count it once, leave its sites as written
            assert len(stale.findall(text)) + (0 if same else len(token(v[col]).findall(text))) == count, (rel, v['name'])
            new_text = text if same else stale.sub(v[col], text)
            if new_text != text:
                path.write_text(new_text)
                changed.append(rel)
    return sorted(set(changed))


def check_stock(fw, table, stock_zip):
    """The tree's patch sites, trampoline prologues, shim literals and strings against one stock ZIP."""
    spec = json.loads((fw/'build-inputs.json').read_text())
    with zipfile.ZipFile(stock_zip) as z:
        ap = z.read('nuttx_ap.bin')
    assert hashlib.sha256(ap).hexdigest() == spec['stockAP'], 'stock ZIP is not the tree stockAP'
    col = column(table, spec['stockBase'])
    out = []
    delta = data_file_delta(ap)
    if table['format'] == 'turboio-rebase-2':
        got = table['bases'][spec['stockBase']].get('dataFileDelta')
        if got is None or int(got, 16) != delta:
            out.append('table dataFileDelta %s is not the stock image\'s %#x' % (got, delta))
    for e in spec['edits']:
        at = int(e['offset'], 16)
        if ap[at:at + len(bytes.fromhex(e['before']))].hex() != e['before']:
            out.append('edit %r before bytes' % e['role'])
    tramp = (fw/'trampolines.S').read_text()
    for e in spec['edits']:
        if e['role'].startswith('Entry trampoline '):
            name = e['role'].removeprefix('Entry trampoline ')
            m = re.search(r'^stock_' + name + r':\n\.byte ([^\n]+)\nb\.w resume_' + name + r'$', tramp, re.M)
            data = bytes(int(x, 0) for x in m.group(1).split(',')) if m else b''
            if data != bytes.fromhex(e['before']):
                out.append('trampoline prologue ' + name)
    values = {v['name']: int(v[col], 16) for v in table['values']}
    reg = next(e for e in spec['edits'] if e['role'] == 'File callback registration')
    site = int(reg['address'], 16)
    for k, name in ((2, 'file_callback_struct'), (4, 'stream_register_target')):
        g = struct.unpack_from('<H', ap, site + k - FLASH)[0]
        literal = struct.unpack_from('<I', ap, ((site + k + 4) & ~3) + (g & 0xff) * 4 - FLASH)[0]
        if (g & 0xf800) != 0x4800 or literal != values[name]:
            out.append('stock registration literal for ' + name)
    for v in table['values']:
        if v['kind'] == 'data':
            text = value_string(table, v, col)
            try:
                at = data_offset(ap, int(v[col], 16))
            except AssertionError:
                out.append('data string %s (address outside the copied data)' % v['name'])
                continue
            if ap[at:at + len(text) + 1] != text.encode() + b'\0':
                out.append('data string ' + v['name'])
    return out


def main():
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--check', action='store_true')
    mode.add_argument('--write', action='store_true')
    parser.add_argument('--to', help='stock base to write (--write)')
    parser.add_argument('--base', help='stock base to check (default: build-inputs.json stockBase)')
    parser.add_argument('--stock', type=Path, help='stock ZIP of that base (--check)')
    parser.add_argument('--tree', type=Path, default=FW)
    parser.add_argument('--table', type=Path, help='table file to use instead of the active one in firmware/baseline')
    args = parser.parse_args()
    fw = args.tree.resolve()
    table_path = args.table or active_table_path(fw)
    table = load_table(args.table, fw)
    if args.write:
        if not args.to:
            parser.error('--write needs --to')
        changed = write(fw, table, args.to)
        left = problems(fw, table, args.to)
        if left:
            raise SystemExit('tree still not on %s:\n  %s' % (args.to, '\n  '.join(left)))
        print(json.dumps({'stockBase': args.to, 'changed': changed}, indent=2))
        return
    base = args.base or json.loads((fw/'build-inputs.json').read_text()).get('stockBase')
    left = problems(fw, table, base)
    if args.stock and not left:
        left = check_stock(fw, table, args.stock)
    if left:
        raise SystemExit('REBASE CHECK FAIL (%s):\n  %s' % (base, '\n  '.join(left)))
    print('PASS rebase: tree wholly on stock %s (table %s: %d link.ld callees, %d edits, %d value sites%s)' % (
        base, Path(table_path).name, len(table['linkld']), len(table['edits']), sum(sum(sites(v).values()) for v in table['values']),
        '; patch sites, trampoline prologues, registration literals and strings match the stock ZIP' if args.stock else ''))


if __name__ == '__main__':
    sys.exit(main())
