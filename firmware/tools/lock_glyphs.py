#!/usr/bin/env python3
"""Generate src/lock-v1/lock_glyphs.h: the ten drawn PIN digits of the glasses lock screen (docs/lock-design.md §3).

Each digit is a set of polylines on a unit box (the shapes of the LensLock board's Option C), scaled into a 34x50 px box
with a 3 px margin and drawn with a 5 px round stroke: a pixel's coverage is clamp(r + 0.5 - d, 0, 1), where d is the
distance from the pixel centre to the nearest segment and r = 2.5. Coverage is stored at 4 bpp (nibble = round(c * 15);
the view expands it to level nibble * 17, so a full pixel is 255, lens-full).

Pixel format (lock_view.c glyph_decode): pos = row*34 + col; nibble = (packed[pos/2] >> (pos%2 ? 0 : 4)) & 15, i.e. an even
pixel is the HIGH nibble. 850 bytes per digit, 8500 in all.

The header also carries, for host tools only (#ifdef TLV_GLYPH_SVG), each digit's polylines as SVG point lists, which the
layout gate writes into the board panel. Standard library only.

usage: lock_glyphs.py [--out HEADER] [--check]
  --check   do not write; exit 1 unless HEADER is byte-identical to the regeneration.
"""
import argparse, math, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
DEFAULT_HEADER = os.path.join(ROOT, "src", "lock-v1", "lock_glyphs.h")
W, H, STROKE = 34, 50, 5
BYTES = W * H // 2  # 850
MAX_POINTS = 24


def _arc(p, cx, cy, rx, ry, a0, a1, steps):
    """Arc of an ellipse, y down (0 deg = right, 90 = down), from a0 to a1 degrees in `steps` pieces."""
    for i in range(steps + 1):
        a = (a0 + (a1 - a0) * i / steps) * math.pi / 180
        p.append((cx + rx * math.cos(a), cy + ry * math.sin(a)))


def unit_lines(d):
    """The digit's polylines on the unit box (x right, y down)."""
    d %= 10
    if d == 0:
        p = []; _arc(p, .5, .3, .5, .3, 180, 360, 10); _arc(p, .5, .7, .5, .3, 0, 180, 10); p.append((0, .3)); return [p]
    if d == 1:
        return [[(.18, .2), (.56, 0), (.56, 1)]]
    if d == 2:
        p = []; _arc(p, .5, .28, .5, .28, 195, 395, 12); p += [(0, 1), (1, 1)]; return [p]
    if d == 3:
        a = []; _arc(a, .48, .25, .46, .25, 200, 450, 12); b = []; _arc(b, .5, .74, .5, .26, 270, 520, 12); return [a, b]
    if d == 4:
        return [[(.72, 1), (.72, 0), (0, .7), (1, .7)]]
    if d == 5:
        p = [(.92, 0), (.1, 0), (.05, .46)]; _arc(p, .5, .68, .5, .32, 215, 520, 14); return [p]
    if d == 6:
        a = []; _arc(a, .5, .7, .5, .3, 0, 360, 16); b = [(0, .7)]; _arc(b, .55, .45, .55, .45, 180, 305, 8); return [a, b]
    if d == 7:
        return [[(0, 0), (1, 0), (.36, 1)]]
    if d == 8:
        a = []; _arc(a, .5, .24, .42, .24, 0, 360, 16); b = []; _arc(b, .5, .73, .5, .27, 0, 360, 16); return [a, b]
    return [[(1 - x, 1 - y) for x, y in line] for line in unit_lines(6)]   # 9: the 6 turned half round


def glyph_lines(d):
    """The polylines in glyph pixels (a 3 px margin keeps the round stroke inside the box)."""
    pad = STROKE / 2 + .5
    out = []
    for line in unit_lines(d):
        assert 2 <= len(line) <= MAX_POINTS
        out.append([(pad + x * (W - 2 * pad), pad + y * (H - 2 * pad)) for x, y in line])
    return out


def _seg_dist(px, py, ax, ay, bx, by):
    dx, dy = bx - ax, by - ay
    l = dx * dx + dy * dy
    t = ((px - ax) * dx + (py - ay) * dy) / l if l > 0 else 0
    t = min(1.0, max(0.0, t))
    x, y = ax + t * dx - px, ay + t * dy - py
    return math.sqrt(x * x + y * y)


def coverage(d):
    """W*H nibbles (0..15), row major."""
    lines = glyph_lines(d)
    segs = [(a[0], a[1], b[0], b[1]) for line in lines for a, b in zip(line, line[1:])]
    r = STROKE / 2
    out = []
    for y in range(H):
        for x in range(W):
            e = min(_seg_dist(x + .5, y + .5, *s) for s in segs)
            c = min(1.0, max(0.0, r + .5 - e))
            out.append(int(round(c * 15)))
    return out


def pack(nibbles):
    assert len(nibbles) == W * H and all(0 <= n <= 15 for n in nibbles)
    return bytes((nibbles[i] << 4) | nibbles[i + 1] for i in range(0, W * H, 2))


def unpack(packed):
    out = []
    for b in packed:
        out += [b >> 4, b & 15]
    return out


def svg_points(line):
    return " ".join("%.2f,%.2f" % (x, y) for x, y in line)


def render_header():
    t = ["/* Generated by tools/lock_glyphs.py; do not edit. The ten drawn PIN digits (docs/lock-design.md §3): 34x50 px, 5 px\n",
         " * round strokes, 4 bpp, an even pixel in the high nibble (level = nibble * 17). 10 x 850 = 8500 bytes. */\n",
         "#ifndef TIO_LOCK_GLYPHS_H\n#define TIO_LOCK_GLYPHS_H\n",
         "_Static_assert(TLV_GLYPH_W==%d&&TLV_GLYPH_H==%d&&TLV_GLYPH_STROKE==%d,\"lock_glyphs.h was generated for this box\");\n" % (W, H, STROKE),
         "static const unsigned char tlv_glyph4[10][%d] = {\n" % BYTES]
    for d in range(10):
        p = pack(coverage(d))
        t.append(" /* %d */ {\n" % d)
        for r in range(0, BYTES, 17):
            t.append("  " + "".join("0x%02x," % b for b in p[r:r + 17]) + "\n")
        t.append(" }" + ("," if d < 9 else "") + "\n")
    t.append("};\n#ifdef TLV_GLYPH_SVG\n/* Host tools only: each digit's polylines in glyph pixels, as SVG points (up to two per digit). */\n")
    t.append("static const char *const tlv_glyph_svg[10][2] = {\n")
    for d in range(10):
        lines = glyph_lines(d)
        assert len(lines) <= 2
        cells = ['"%s"' % svg_points(l) for l in lines] + ["0"] * (2 - len(lines))
        t.append(" {" + ", ".join(cells) + "}" + ("," if d < 9 else "") + "\n")
    t.append("};\n#endif\n#endif\n")
    return "".join(t)


def parse_header(text):
    """The ten packed digits of a header (inverse of render_header's table)."""
    body = text[text.index("tlv_glyph4"):text.index("#ifdef TLV_GLYPH_SVG")]
    vals = [int(x, 16) for x in re.findall(r"0x([0-9a-f]{2})", body)]
    assert len(vals) == 10 * BYTES, len(vals)
    return [bytes(vals[i * BYTES:(i + 1) * BYTES]) for i in range(10)]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=DEFAULT_HEADER)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render_header()
    if a.check:
        have = open(a.out, "rb").read() if os.path.exists(a.out) else b""
        if have != text.encode("utf-8"):
            print("lock_glyphs.h differs from the regeneration (run: python3 -I tools/lock_glyphs.py)")
            return 1
        print("lock_glyphs.h matches the regeneration")
        return 0
    with open(a.out, "wb") as f:
        f.write(text.encode("utf-8"))
    print("wrote %s (%d bytes of glyphs)" % (os.path.relpath(a.out, ROOT), 10 * BYTES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
