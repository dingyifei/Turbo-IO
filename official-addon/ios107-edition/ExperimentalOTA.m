static id Fail(NSError **error,NSString *message){if(error)*error=[NSError errorWithDomain:@"TurboIO.ExperimentalOTA" code:1 userInfo:@{NSLocalizedDescriptionKey:message}];return nil;}
NSDictionary *TIOCheckExperimentalOTA(NSData *data,NSError **error){
    if(data.length!=TIO_FW_ZIP_BYTES)return Fail(error,[NSString stringWithFormat:TIOText(@"ota.identity.sizeMismatch"),TIO_FW_NAME]);
    unsigned char digest[CC_SHA256_DIGEST_LENGTH];CC_SHA256(data.bytes,(CC_LONG)data.length,digest);
    NSMutableString *hex=[NSMutableString new];for(NSUInteger i=0;i<sizeof(digest);i++)[hex appendFormat:@"%02x",digest[i]];
    if(![hex isEqual:TIOExperimentalOTASHA()])return Fail(error,TIOText(@"SHA-256 不匹配。拒绝未知、旧版或已修改的包，未发送。"));
    // The exact archive has independently passed full ZIP/manifest/AP auditing
    // on Mac. This is exact-byte identity, not a generic ZIP manifest parser.
    return @{@"schema":@1,@"candidate":[@"Turbo Menu " stringByAppendingString:TIO_FW_NAME],@"baseFirmware":TIO_FW_BASE,
             @"archiveSHA256":hex,@"archiveBytes":@(data.length),@"changedPayloads":@[@"nuttx_ap.bin"],
             @"unchangedPayloadCount":@(TIOExperimentalOTAMemberCount()-2),@"integrityPassed":@YES,@"sent":@NO,
             @"runtimeValidated":@NO,@"officialDispatchConnected":@NO};
}
static NSData *Read(NSURL *source,NSError **error){
    if(!source.isFileURL)return Fail(error,TIOText(@"只接受本地文件。"));
    NSInputStream *stream=[NSInputStream inputStreamWithURL:source];[stream open];
    NSMutableData *data=[NSMutableData new];uint8_t buffer[65536];NSInteger n;
    while((n=[stream read:buffer maxLength:sizeof(buffer)])>0){
        if(data.length+(NSUInteger)n>TIO_FW_ZIP_BYTES){[stream close];return Fail(error,TIOText(@"文件过大；未保存、未发送。"));}
        [data appendBytes:buffer length:(NSUInteger)n];
    }
    NSError *readError=stream.streamError;[stream close];
    if(n<0||readError){if(error)*error=readError?:[NSError errorWithDomain:@"TurboIO.ExperimentalOTA" code:2 userInfo:@{NSLocalizedDescriptionKey:TIOText(@"无法读取文件")}];return nil;}
    return TIOCheckExperimentalOTA(data,error)?data:nil;
}
NSDictionary *TIOReadExperimentalOTA(NSURL *file,NSError **error){NSData *data=Read(file,error);return data?TIOCheckExperimentalOTA(data,error):nil;}
NSDictionary *TIOImportExperimentalOTA(NSURL *source,NSURL *directory,NSError **error){
    if(!directory.isFileURL)return Fail(error,TIOText(@"只接受本地目录。"));
    NSData *data=Read(source,error);if(!data)return nil;
    NSDictionary *result=TIOCheckExperimentalOTA(data,error);
    NSFileManager *fm=NSFileManager.defaultManager;
    if(![fm createDirectoryAtURL:directory withIntermediateDirectories:YES attributes:@{NSFilePosixPermissions:@0700} error:error])return nil;
    if(![directory setResourceValue:@YES forKey:NSURLIsExcludedFromBackupKey error:error])return nil;
    NSURL *destination=[directory URLByAppendingPathComponent:[TIOExperimentalOTASHA() stringByAppendingString:@".zip"]];
    if([fm fileExistsAtPath:destination.path]){
        if(!TIOReadExperimentalOTA(destination,error))return nil;
    }else{
        // Exclusive creation; no official cache or existing imported file replaced.
        if(![data writeToURL:destination options:NSDataWritingWithoutOverwriting error:error])return nil;
    }
    if(![fm setAttributes:@{NSFilePosixPermissions:@0600} ofItemAtPath:destination.path error:error])return nil;
#if TARGET_OS_IPHONE
    if(![fm setAttributes:@{NSFileProtectionKey:NSFileProtectionCompleteUntilFirstUserAuthentication} ofItemAtPath:destination.path error:error])return nil;
#endif
    return result;
}

// The members of the release ZIP (manifest, AP and the stock members of its base: 17 on the 1.0.6.11
// base), generated by firmware/tools/phone_pins.py from the ZIP; the release is chosen at compile
// time (FirmwarePins.h). Member names are flat: a name holding a path separator would fail closed (PinsUsable).
static NSDictionary *PayloadPins(void){return TIO_FW_MEMBER_PINS;}
static BOOL PinsUsable(NSDictionary *pins){
    if(pins.count<3||!pins[@"OtaFileInfo.json"]||!pins[@"nuttx_ap.bin"])return NO;
    for(NSString *name in pins)if(![name isKindOfClass:NSString.class]||!name.length||[name containsString:@"/"]||[name hasPrefix:@"."])return NO;
    return YES;
}
NSUInteger TIOExperimentalOTAMemberCount(void){return PayloadPins().count;}
// Reads each pinned member by name from the folder: a regular file (never a link, FIFO or device) of the
// pinned size whose SHA-256 is the member pin. Returns those bytes, held in memory; the gate compares
// every slice with exactly them. Other files in the folder are not read. Never modifies anything.
NSDictionary<NSString *,NSData *> *TIOCopyExperimentalOTAPayloads(NSURL *directory,NSError **error){
    if(!directory.isFileURL)return Fail(error,TIOText(@"只接受本地待传目录。"));
    NSDictionary *pins=PayloadPins();if(!PinsUsable(pins))return Fail(error,[NSString stringWithFormat:TIOText(@"ota.identity.fileSetMismatch"),TIO_FW_NAME]);
    int root=open(directory.path.fileSystemRepresentation,O_RDONLY|O_DIRECTORY|O_NOFOLLOW|O_CLOEXEC);
    if(root<0)return Fail(error,TIOText(@"待传目录不存在、不可读或为符号链接；未发送。"));
    NSMutableDictionary *copy=[NSMutableDictionary new];
    for(NSString *name in [pins.allKeys sortedArrayUsingSelector:@selector(compare:)]){
        NSUInteger expected=[pins[name][0] unsignedIntegerValue];NSMutableData *data=nil;struct stat item;
        int fd=openat(root,name.fileSystemRepresentation,O_RDONLY|O_NOFOLLOW|O_NONBLOCK|O_CLOEXEC);
        if(fd>=0&&fstat(fd,&item)==0&&S_ISREG(item.st_mode)&&item.st_size==(off_t)expected){
            data=[NSMutableData dataWithLength:expected];NSUInteger total=0;ssize_t n=0;
            while(data&&total<expected){n=read(fd,(uint8_t *)data.mutableBytes+total,expected-total);if(n<0&&errno==EINTR)continue;if(n<=0){data=nil;break;}total+=(NSUInteger)n;}
            uint8_t extra;if(data&&read(fd,&extra,1)!=0)data=nil;
        }
        if(fd>=0)close(fd);
        if(data){
            uint8_t digest[CC_SHA256_DIGEST_LENGTH];CC_SHA256(data.bytes,(CC_LONG)data.length,digest);
            NSMutableString *hex=[NSMutableString new];for(NSUInteger i=0;i<sizeof(digest);i++)[hex appendFormat:@"%02x",digest[i]];
            if(![hex isEqual:pins[name][1]])data=nil;
        }
        if(!data){close(root);return Fail(error,[NSString stringWithFormat:TIOText(@"ota.identity.payloadMismatch"),name,TIO_FW_NAME]);}
        copy[name]=[data copy];
    }
    close(root);return [copy copy];
}
// The official ota/<folder> check: every pinned member reads back as above.
NSDictionary *TIOCheckOfficialOTADirectory(NSURL *directory,NSError **error){
    NSDictionary *files=TIOCopyExperimentalOTAPayloads(directory,error);if(!files)return nil;
    return @{@"candidate":[@"Turbo Menu " stringByAppendingString:TIO_FW_NAME],@"checkedMembers":@(files.count),@"integrityPassed":@YES,@"transferSessionBound":@NO,@"sent":@NO,@"flashAuthorized":@NO};
}
