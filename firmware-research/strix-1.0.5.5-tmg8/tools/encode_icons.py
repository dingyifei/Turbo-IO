#!/usr/bin/env python3
"""Encode the 48x48 PNG masters into src/focus-v1/focus_menu_icons.h (4 bpp, 13 x 1152 B).

Pixel format (focus_menu.c icon()):
  pos = row*48 + col; nibble = (packed[pos/2] >> (pos%2 ? 0 : 4)) & 15
  i.e. an even pixel is the HIGH nibble, an odd pixel the LOW nibble; stride 24 B per row, 1152 B per icon.
  nibble = level/17 (integer division) from the master's green channel; the lens is green-only.
Icon order is the menu index: the NN- prefix of the master file name, in the order of focus_menu.c names[].
Masters are the 48x48 rasterisations of assets/menu-icons/svg/NN-name.svg made with
  rsvg-convert -w 48 -h 48 -b black NN-name.svg -o png/NN-name.png
(see assets/menu-icons/README.md). That step is documented, not part of this tool or its test.
Standard library only; reads 8-bit grey, RGB or RGBA non-interlaced PNGs.

usage: encode_icons.py [--masters DIR] [--out HEADER] [--check]
  --check   do not write; exit 1 unless HEADER is byte-identical to the regeneration.
"""
import argparse, os, re, struct, sys, zlib

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
DEFAULT_MASTERS = os.path.join(ROOT, "assets", "menu-icons", "png")
DEFAULT_HEADER = os.path.join(ROOT, "src", "focus-v1", "focus_menu_icons.h")
NAMES = ["recorder", "live-captions", "live-assist", "todo", "teleprompter", "lifelog",
         "do-not-disturb", "display-test", "navigation", "music", "pomodoro", "my-apps", "camera"]
N, W = len(NAMES), 48
ICON_BYTES = W * W // 2  # 1152


def read_png_levels(path):
    """Return the 48x48 gray levels (green channel) of a master; the master must be grey (R == G == B)."""
    data = open(path, "rb").read()
    if data[:8] != b"\x89PNG\r\n\x1a\n":
        raise ValueError(path + ": not a PNG")
    pos, idat, hdr = 8, b"", None
    while pos < len(data):
        ln, typ = struct.unpack(">I4s", data[pos:pos + 8])
        body = data[pos + 8:pos + 8 + ln]
        if typ == b"IHDR":
            hdr = struct.unpack(">IIBBBBB", body)
        elif typ == b"IDAT":
            idat += body
        pos += 12 + ln
    w, h, depth, ctype, _, _, interlace = hdr
    if (w, h) != (W, W) or depth != 8 or ctype not in (0, 2, 6) or interlace:
        raise ValueError("%s: need 48x48, 8-bit grey/RGB/RGBA, not interlaced (got %dx%d depth %d type %d)"
                         % (path, w, h, depth, ctype))
    ch = {0: 1, 2: 3, 6: 4}[ctype]
    raw = zlib.decompress(idat)
    stride, prev, rows, p = w * ch, bytearray(w * ch), [], 0
    for _ in range(h):
        flt, line = raw[p], bytearray(raw[p + 1:p + 1 + stride])
        p += 1 + stride
        for i in range(stride):
            a = line[i - ch] if i >= ch else 0
            b = prev[i]
            c = prev[i - ch] if i >= ch else 0
            if flt == 1:
                line[i] = (line[i] + a) & 255
            elif flt == 2:
                line[i] = (line[i] + b) & 255
            elif flt == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif flt == 4:
                pa, pb, pc = abs(b - c), abs(a - c), abs(a + b - 2 * c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
            elif flt != 0:
                raise ValueError(path + ": bad PNG filter")
        rows.append(line)
        prev = line
    levels = []
    for line in rows:
        for x in range(w):
            px = line[x * ch:(x + 1) * ch]
            if ch >= 3 and not (px[0] == px[1] == px[2]):
                raise ValueError(path + ": master is not grey")
            if ch == 4 and px[3] != 255:
                raise ValueError(path + ": master has transparency; rasterise with -b black")
            levels.append(px[1] if ch >= 3 else px[0])
    return levels


def encode(levels):
    """Row-major levels 0..255 -> 1152 packed bytes, even pixel high nibble, nibble = level // 17."""
    assert len(levels) == W * W
    out = bytearray(ICON_BYTES)
    for pos, lv in enumerate(levels):
        nib = lv // 17
        out[pos // 2] |= nib if pos % 2 else nib << 4
    return bytes(out)


def master_paths(masters):
    found = sorted(f for f in os.listdir(masters) if f.endswith(".png"))
    want = ["%02d-%s.png" % (i, n) for i, n in enumerate(NAMES)]
    if found != want:
        raise ValueError("masters in %s must be exactly %s, found %s" % (masters, want, found))
    return [os.path.join(masters, f) for f in want]


def render_header(packed):
    assert len(packed) == N and all(len(p) == ICON_BYTES for p in packed)
    t = ["/* Generated by encode_icons.py; %d x 48 x 48 / 2 = %d bytes. */\n" % (N, N * ICON_BYTES),
         "#ifndef TMG1_ICONS_H\n#define TMG1_ICONS_H\n",
         "static const unsigned char fm_icon4[%d][%d] = {\n" % (N, ICON_BYTES)]
    for i, p in enumerate(packed):
        t.append(" /* menu index %d */ {\n" % i)
        for r in range(W):
            t.append("  " + "".join("0x%02x," % b for b in p[r * 24:(r + 1) * 24]) + "\n")
        t.append(" }" + ("," if i < N - 1 else "") + "\n")
    t.append("};\n#endif\n")
    return "".join(t)


def parse_header(text):
    """Inverse of render_header (used by the tests to round-trip the committed header)."""
    body = text[text.index("fm_icon4"):]
    vals = [int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body)]
    assert len(vals) == N * ICON_BYTES, len(vals)
    return [bytes(vals[i * ICON_BYTES:(i + 1) * ICON_BYTES]) for i in range(N)]


def regenerate(masters=DEFAULT_MASTERS):
    return render_header([encode(read_png_levels(p)) for p in master_paths(masters)])


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--masters", default=DEFAULT_MASTERS)
    ap.add_argument("--out", default=DEFAULT_HEADER)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = regenerate(a.masters)
    if a.check:
        if open(a.out, "rb").read() != text.encode("ascii"):
            print("ENCODE_ICONS_MISMATCH: %s differs from the regeneration of %s" % (a.out, a.masters))
            return 1
        print("ENCODE_ICONS_OK: %s is byte-identical to the regeneration (%d bytes of art)" % (a.out, N * ICON_BYTES))
        return 0
    with open(a.out, "wb") as f:
        f.write(text.encode("ascii"))
    print("wrote %s (%d icons, %d bytes of art)" % (a.out, N, N * ICON_BYTES))
    return 0


if __name__ == "__main__":
    sys.exit(main())
