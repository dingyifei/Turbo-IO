static id Fail(NSError **error,NSString *message){if(error)*error=[NSError errorWithDomain:@"TurboIO.ExperimentalOTA" code:1 userInfo:@{NSLocalizedDescriptionKey:message}];return nil;}
// Member names are flat: a name holding a path separator would fail closed. The manifest and the AP must be pinned.
static BOOL PinsUsable(NSDictionary *pins){
    if(![pins isKindOfClass:NSDictionary.class]||pins.count<3||!pins[@"OtaFileInfo.json"]||!pins[@"nuttx_ap.bin"])return NO;
    for(NSString *name in pins){
        if(![name isKindOfClass:NSString.class]||!name.length||[name containsString:@"/"]||[name hasPrefix:@"."])return NO;
        NSArray *pin=pins[name];if(![pin isKindOfClass:NSArray.class]||pin.count!=2||![pin[0] isKindOfClass:NSNumber.class]||![pin[1] isKindOfClass:NSString.class]||[pin[1] length]!=64)return NO;
    }
    return YES;
}
static BOOL PackageUsable(NSDictionary *p){
    return [p isKindOfClass:NSDictionary.class]&&[p[@"name"] isKindOfClass:NSString.class]&&[p[@"name"] length]&&([p[@"kind"] isEqual:@"TMG"]||[p[@"kind"] isEqual:@"STOCK"])
        &&[p[@"resource"] isKindOfClass:NSString.class]&&[p[@"zipBytes"] isKindOfClass:NSNumber.class]&&[p[@"zipBytes"] unsignedIntegerValue]>0
        &&[p[@"zipSHA256"] isKindOfClass:NSString.class]&&[p[@"zipSHA256"] length]==64&&[p[@"otaVersion"] isKindOfClass:NSString.class]&&[p[@"otaVersion"] length]
        &&[p[@"acceptOsVersions"] isKindOfClass:NSArray.class]&&[p[@"acceptQueryCodes"] isKindOfClass:NSArray.class]&&PinsUsable(p[@"memberPins"]);
}
// The packages of the release chosen at compile time (FirmwarePins.h), generated by firmware/tools/phone_pins.py
// from the release ZIPs. The table is read once; an unusable entry is never handed out.
static NSArray<NSDictionary *> *Packages(void){static NSArray *packages;static dispatch_once_t once;dispatch_once(&once,^{packages=TIO_FW_PACKAGES;});return packages;}
NSUInteger TIOOTAPackageCount(void){return Packages().count;}
NSDictionary *TIOOTAPackageAt(NSUInteger index){NSArray *all=Packages();if(index>=all.count||!PackageUsable(all[index]))return nil;return all[index];}
NSString *TIOOTAPackageDisplayName(NSDictionary *package){
    if(!PackageUsable(package))return @"?";
    if([package[@"kind"] isEqual:@"STOCK"])return [NSString stringWithFormat:TIOText(@"ota.package.stockName"),TIO_FW_BASE];
    return package[@"name"];
}
NSString *TIOOTAPackageArchiveName(NSDictionary *package){return PackageUsable(package)?[package[@"zipSHA256"] stringByAppendingString:@".zip"]:@"";}
static NSString *SHA256Hex(NSData *data){
    unsigned char digest[CC_SHA256_DIGEST_LENGTH];CC_SHA256(data.bytes,(CC_LONG)data.length,digest);
    NSMutableString *hex=[NSMutableString new];for(NSUInteger i=0;i<sizeof(digest);i++)[hex appendFormat:@"%02x",digest[i]];return hex;
}
NSArray<NSString *> *TIOOTAChangedPayloads(NSDictionary *package){
    NSDictionary *pins=package[@"memberPins"],*stock=nil;NSMutableArray *changed=[NSMutableArray array];
    if(![pins isKindOfClass:NSDictionary.class]||[package[@"kind"] isEqual:@"STOCK"])return changed;
    for(NSUInteger i=0;i<TIOOTAPackageCount();i++){NSDictionary *p=TIOOTAPackageAt(i);if([p[@"kind"] isEqual:@"STOCK"])stock=p[@"memberPins"];}
    for(NSString *name in [pins.allKeys sortedArrayUsingSelector:@selector(compare:)]){
        if([name isEqual:@"OtaFileInfo.json"])continue;
        if(stock?![stock[name] isEqual:pins[name]]:[name isEqual:@"nuttx_ap.bin"])[changed addObject:name];   // no stock package: the AP is the TMG change
    }
    return changed;
}
NSDictionary *TIOCheckExperimentalOTA(NSData *data,NSDictionary *package,NSError **error){
    if(!PackageUsable(package))return Fail(error,TIOText(@"ota.package.unknown"));
    if(![data isKindOfClass:NSData.class]||data.length!=[package[@"zipBytes"] unsignedIntegerValue])return Fail(error,[NSString stringWithFormat:TIOText(@"ota.identity.sizeMismatch"),TIOOTAPackageDisplayName(package)]);
    NSString *hex=SHA256Hex(data);
    if(![hex isEqual:package[@"zipSHA256"]])return Fail(error,TIOText(@"SHA-256 不匹配。拒绝未知、旧版或已修改的包，未发送。"));
    // The exact archive has independently passed full ZIP/manifest/AP auditing
    // on Mac (phone_pins.py). This is exact-byte identity, not a generic ZIP manifest parser.
    BOOL stock=[package[@"kind"] isEqual:@"STOCK"];NSUInteger members=[package[@"memberPins"] count];NSArray *changed=TIOOTAChangedPayloads(package);
    return @{@"schema":@1,@"candidate":stock?TIOOTAPackageDisplayName(package):[@"Turbo Menu " stringByAppendingString:package[@"name"]],@"package":package[@"name"],@"baseFirmware":TIO_FW_BASE,
             @"archiveSHA256":hex,@"archiveBytes":@(data.length),@"changedPayloads":changed,
             @"unchangedPayloadCount":@(members-1-changed.count),@"integrityPassed":@YES,@"sent":@NO,
             @"runtimeValidated":@NO,@"officialDispatchConnected":@NO};
}
static NSData *Read(NSURL *source,NSDictionary *package,NSError **error){
    if(!PackageUsable(package))return Fail(error,TIOText(@"ota.package.unknown"));
    if(!source.isFileURL)return Fail(error,TIOText(@"只接受本地文件。"));
    NSInputStream *stream=[NSInputStream inputStreamWithURL:source];[stream open];
    NSMutableData *data=[NSMutableData new];uint8_t buffer[65536];NSInteger n;NSUInteger limit=[package[@"zipBytes"] unsignedIntegerValue];
    while((n=[stream read:buffer maxLength:sizeof(buffer)])>0){
        if(data.length+(NSUInteger)n>limit){[stream close];return Fail(error,TIOText(@"文件过大；未保存、未发送。"));}
        [data appendBytes:buffer length:(NSUInteger)n];
    }
    NSError *readError=stream.streamError;[stream close];
    if(n<0||readError){if(error)*error=readError?:[NSError errorWithDomain:@"TurboIO.ExperimentalOTA" code:2 userInfo:@{NSLocalizedDescriptionKey:TIOText(@"无法读取文件")}];return nil;}
    return TIOCheckExperimentalOTA(data,package,error)?data:nil;
}
NSDictionary *TIOReadExperimentalOTA(NSURL *file,NSDictionary *package,NSError **error){NSData *data=Read(file,package,error);return data?TIOCheckExperimentalOTA(data,package,error):nil;}
NSDictionary *TIOImportExperimentalOTA(NSURL *source,NSURL *directory,NSDictionary *package,NSError **error){
    if(!directory.isFileURL)return Fail(error,TIOText(@"只接受本地目录。"));
    NSData *data=Read(source,package,error);if(!data)return nil;
    NSDictionary *result=TIOCheckExperimentalOTA(data,package,error);
    NSFileManager *fm=NSFileManager.defaultManager;
    if(![fm createDirectoryAtURL:directory withIntermediateDirectories:YES attributes:@{NSFilePosixPermissions:@0700} error:error])return nil;
    if(![directory setResourceValue:@YES forKey:NSURLIsExcludedFromBackupKey error:error])return nil;
    // Each package has its own file, named by its SHA-256, so the two packages never share a copy.
    NSURL *destination=[directory URLByAppendingPathComponent:TIOOTAPackageArchiveName(package)];
    if([fm fileExistsAtPath:destination.path]){
        if(!TIOReadExperimentalOTA(destination,package,error))return nil;
    }else{
        // Exclusive creation; no official cache or existing imported file replaced.
        if(![data writeToURL:destination options:NSDataWritingWithoutOverwriting error:error])return nil;
    }
    if(![fm setAttributes:@{NSFilePosixPermissions:@0600} ofItemAtPath:destination.path error:error])return nil;
#if TARGET_OS_IPHONE
    if(![fm setAttributes:@{NSFileProtectionKey:NSFileProtectionCompleteUntilFirstUserAuthentication} ofItemAtPath:destination.path error:error])return nil;
#endif
    return result;
}

// Reads each member the package pins by name from the folder: a regular file (never a link, FIFO or device) of the
// pinned size whose SHA-256 is the member pin. Returns those bytes, held in memory; the gate compares every slice
// with exactly them. Other files in the folder are not read. Never modifies anything. A folder that holds the other
// package fails here (its AP and manifest differ), with the member message naming this package.
NSDictionary<NSString *,NSData *> *TIOCopyExperimentalOTAPayloads(NSURL *directory,NSDictionary *package,NSError **error){
    if(!PackageUsable(package))return Fail(error,TIOText(@"ota.package.unknown"));
    if(!directory.isFileURL)return Fail(error,TIOText(@"只接受本地待传目录。"));
    NSDictionary *pins=package[@"memberPins"];NSString *label=TIOOTAPackageDisplayName(package);
    int root=open(directory.path.fileSystemRepresentation,O_RDONLY|O_DIRECTORY|O_NOFOLLOW|O_CLOEXEC);
    if(root<0)return Fail(error,TIOText(@"待传目录不存在、不可读或为符号链接；未发送。"));
    NSMutableDictionary *copy=[NSMutableDictionary new];
    for(NSString *name in [pins.allKeys sortedArrayUsingSelector:@selector(compare:)]){
        NSUInteger expected=[pins[name][0] unsignedIntegerValue];NSMutableData *data=nil;struct stat item;
        int fd=openat(root,name.fileSystemRepresentation,O_RDONLY|O_NOFOLLOW|O_NONBLOCK|O_CLOEXEC);
        if(fd>=0&&fstat(fd,&item)==0&&S_ISREG(item.st_mode)&&item.st_size==(off_t)expected){
            data=[NSMutableData dataWithLength:expected];NSUInteger total=0;ssize_t n=0;
            while(data&&total<expected){n=read(fd,(uint8_t *)data.mutableBytes+total,expected-total);if(n<0&&errno==EINTR)continue;if(n<=0){data=nil;break;}total+=(NSUInteger)n;}
            uint8_t extra;if(data&&read(fd,&extra,1)!=0)data=nil;
        }
        if(fd>=0)close(fd);
        if(data&&![SHA256Hex(data) isEqual:pins[name][1]])data=nil;
        if(!data){close(root);return Fail(error,[NSString stringWithFormat:TIOText(@"ota.identity.payloadMismatch"),name,label]);}
        copy[name]=[data copy];
    }
    close(root);return [copy copy];
}
// The official ota/<folder> check for the package: every member it pins reads back as above.
NSDictionary *TIOCheckOfficialOTADirectory(NSURL *directory,NSDictionary *package,NSError **error){
    NSDictionary *files=TIOCopyExperimentalOTAPayloads(directory,package,error);if(!files)return nil;
    BOOL stock=[package[@"kind"] isEqual:@"STOCK"];
    return @{@"candidate":stock?TIOOTAPackageDisplayName(package):[@"Turbo Menu " stringByAppendingString:package[@"name"]],@"package":package[@"name"],@"checkedMembers":@(files.count),@"integrityPassed":@YES,@"transferSessionBound":@NO,@"sent":@NO,@"flashAuthorized":@NO};
}
